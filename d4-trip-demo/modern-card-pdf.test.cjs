'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'modern-card-pdf.css'),'utf8');
const js=fs.readFileSync(path.join(__dirname,'modern-card-pdf.js'),'utf8');
assert.match(html,/modern-card-pdf\.js\?build=46/);
assert.match(html,/modern-card-pdf\.css\?build=46/);
assert.match(html,/D4ModernCardPDF\.render\(t,calculations\(t\),collectionTotals\(t\),datesInTrip\(t\)\)/);
assert.match(css,/@page\{size:A4/);
assert.match(css,/display:table-header-group/);
const env={window:{},Date};
vm.runInNewContext(js,env);
const trip={name:'Goa <Trip>',destination:'Goa',start:'2026-11-24',end:'2026-11-26',members:['A','B'],expenses:[{date:'2026-11-24',category:'Food',note:'Breakfast',paidBy:'A',method:'UPI',amount:100}],plans:[{date:'2026-11-24',time:'09:00',title:'Arrival',place:'Madgaon',done:false}],notes:[],files:[],collection:{payments:[]}};
const calc={total:100,categories:{Food:100},daily:{'2026-11-24':100}};
const col={paid:50,pending:150,rows:[{member:'A',target:200,paid:50,pending:150,status:'Pending'}]};
const result=env.window.D4ModernCardPDF.render(trip,calc,col,['2026-11-24','2026-11-25','2026-11-26']);
assert.equal((result.match(/class="mc-page /g)||[]).length,6);
for(const heading of ['Trip Report','Trip Overview','Member Payments','Expense Summary','Day Plan & Milestones','Trip Summary'])assert.ok(result.includes(heading),heading);
assert.match(result,/Goa &lt;Trip&gt;/);
assert.doesNotMatch(result,/<Trip>/);
assert.match(result,/₹100/);
assert.match(result,/₹150/);
assert.match(result,/Upcoming/);
assert.match(result,/Trip Progress Report/);
trip.plans[0].done=true;
assert.match(env.window.D4ModernCardPDF.render(trip,calc,col,['2026-11-24']),/Trip Completed!/);
assert.equal(trip.expenses[0].amount,100,'PDF must not mutate trip data');
console.log('PASS: Modern Card six-page report, real totals, escaping, incomplete vs complete status');
